#!/usr/bin/env python3
"""Convert the supplied MTGJSON set to reproducible game data (standard library only).
Run only when updating the source JSON; Visual Studio builds need no Python.
"""
import argparse
import json
import re
from pathlib import Path


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--input', type=Path, default=Path('data/source/2ED.json'))
    parser.add_argument('--root', type=Path, default=Path('.'))
    args = parser.parse_args()
    source = json.loads(args.input.read_text(encoding='utf-8'))
    data = source['data']
    if data['code'] != '2ED':
        raise ValueError('This milestone imports Unlimited (2ED); do not silently replace it with another set.')
    cards = sorted(data['cards'], key=lambda c: int(c['number']))
    if len(cards) != 302:
        raise ValueError('Expected the supplied 302-record Unlimited set.')
    palette = {'W': (.80,.72,.49), 'U': (.28,.43,.68), 'B': (.34,.28,.40),
               'R': (.73,.34,.28), 'G': (.26,.48,.31)}
    rows, manifest, normalized = [], [], []
    for c in cards:
        sid = c['identifiers']['scryfallId']
        if not re.fullmatch(r'[0-9a-f]{8}(?:-[0-9a-f]{4}){3}-[0-9a-f]{12}', sid):
            raise ValueError('Invalid printing identifier')
        identity = ''.join(c.get('colorIdentity', []))
        color = palette.get(identity, (.48,.42,.38))
        basic = 'Basic' in c.get('supertypes', [])
        rules = c.get('originalText', c.get('text', ''))
        original_type = c.get('originalType', c['type'])
        power = c['power'] + '/' + c['toughness'] if 'power' in c and 'toughness' in c else ''
        entry = {'id': c['uuid'], 'name': c['name'], 'type': original_type,
                 'mana_cost': c.get('manaCost', ''), 'rules_text': rules, 'power_toughness': power,
                 'set_id': '2ed', 'rarity': c['rarity'], 'collector_number': c['number'],
                 'scryfall_id': sid, 'oracle_text': c.get('text', ''),
                 'color_identity': identity, 'is_basic_land': basic}
        normalized.append(entry)
        # JSON string escaping is valid for the UTF-8 strings used here in C++.
        quote = lambda s: json.dumps(s, ensure_ascii=False)
        fields = [entry[k] for k in ['id','name','type','mana_cost','rules_text','power_toughness']]
        metadata = [entry[k] for k in ['set_id','rarity','collector_number','scryfall_id','oracle_text','color_identity']]
        rows.append('    {' + ','.join(quote(v) for v in fields) + ',{' + ','.join(f'{v:.2f}F' for v in color) + '},' + ','.join(quote(v) for v in metadata) + ',' + ('true' if basic else 'false') + '},')
        manifest.append({'name': c['name'], 'number': c['number'], 'scryfall_id': sid,
                         'metadata_url': f'https://api.scryfall.com/cards/{sid}', 'cache_file': sid + '.jpg'})
    if len({c['id'] for c in normalized}) != len(cards) or len({c['scryfall_id'] for c in normalized}) != len(cards):
        raise ValueError('Duplicate card or printing IDs')
    paths = {'src/cards/UnlimitedCards.inc': '// Generated by tools/import_mtgjson.py from the supplied 2ED.json.\n' + '\n'.join(rows) + '\n',
             'data/sets/unlimited.json': json.dumps({'set_id':'2ed','name':data['name'],'source':source['meta'], 'cards':normalized, 'booster':data.get('booster',{})}, indent=2, ensure_ascii=False) + '\n',
             'data/sets/unlimited-images.json': json.dumps({'set_id':'2ed','cards':manifest}, indent=2, ensure_ascii=False) + '\n'}
    for path, content in paths.items():
        target = args.root / path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content, encoding='utf-8')
    print(f'Imported {len(cards)} Unlimited printings, {sum(c["is_basic_land"] for c in normalized)} basic-land variants. No images downloaded.')


if __name__ == '__main__':
    main()
